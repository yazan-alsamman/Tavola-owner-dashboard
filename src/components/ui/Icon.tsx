export function MaterialIcon({ name, filled, className, size = 20 }: MaterialIconProps) {
  const Icon = ICON_MAP[name] ?? CircleHelp
  const props: LucideProps = {
    size,
    className: cn('shrink-0', className),
    strokeWidth: filled ? 2.5 : 2,
    'aria-hidden': true,
  }
  return <Icon {...props} />
}

